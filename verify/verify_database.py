"""Check the release asset database-v2.tar.gz (the database [D], version 2) against this repository.

Usage, from the repository root, after downloading the asset:
    python3 verify/verify_database.py [database-v2.tar.gz] [report.json]
    python3 verify/verify_database.py [database-v2.tar.gz] --label 32.62208.1      (print one record)
The asset is the argument ending in .tar.gz, by default database-v2.tar.gz in the repository root.  Without the
asset the script prints SKIP and exits with status 0, so that the other checks can run on a copy without assets.
(Version 1, database-v1.tar.gz, can be given as the argument too; it fails check E for the 182 lattices with
Aut L = C_8 or C_16, whose generators in version 1 generate only C_4.)

Needs only the Python standard library.  Exit status 0 means that every check passed.  All arithmetic is exact
integer arithmetic.  The full check reads all 143,329 lattices and takes about half an hour and about 1.2 GB of memory.

What is checked:
  A  the manifest: every file of rows has the listed size, SHA-256 digest and number of rows, 143,329 rows in all;
  B  the index: one line per lattice, every label of data/classified-lattices.jsonl exactly once, each pointing to
     the line of its file that has this label; the part of Theorem B of each file is that of its lattices in
     data/classified-lattices.jsonl, and the order |Aut L| in each label is the order recorded there;
  C  each Gram matrix: integer, even, positive definite (all leading minors positive) and of determinant 1;
  D  each generator: a 32 x 32 integer matrix g with g^T G g = G (so det g = +-1, as det G = 1);
  E  generation, for the 143,316 lattices with |Aut L| <= 10^6: the exact orbit of an integer vector v under the
     group H generated by the stored generators (v -> g v) has exactly |Aut L| elements.  By D, H is a subgroup of
     Aut L, so |orbit| <= |H| <= |Aut L|; equality shows H = Aut L, given the order |Aut L| of the label (which is
     the order of the first paper).  The vectors are pseudo-random with entries in [-40, 40], seeded by the label;
     up to four are tried before a lattice counts as a failure.
Not checked: generation for the 13 lattices with |Aut L| > 10^6 (their orbits are too large for this script; the
generators are checked by D only); that the lattices have no roots; that the order in the label is |Aut L|; and that
different labels are different lattices.  These are statements of the first paper (Theorems A and B) and rest on its
proofs.
"""
import gzip
import hashlib
import io
import json
import random
import sys
import tarfile
import time
from operator import mul
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
CLASSIFIED = ROOT / 'data/classified-lattices.jsonl'
ROWS = 143329
N = 32
ORBIT_BOUND = 10 ** 6
TRIES = 4


class Checks:
    def __init__(self):
        self.results = []

    def __call__(self, section, name, ok, detail=''):
        self.results.append({'section': section, 'check': name, 'ok': bool(ok), 'detail': str(detail)})
        print('PASS' if ok else 'FAIL', section, name, detail, flush=True)


def unpack(u):
    G = [[0] * N for _ in range(N)]
    k = 0
    for i in range(N):
        for j in range(i, N):
            G[i][j] = G[j][i] = u[k]
            k += 1
    return G


def positive_unimodular(G):
    """Leading minors by Bareiss elimination without row exchanges: all positive, the last equal to 1."""
    m = [r[:] for r in G]
    prev = 1
    for k in range(N):
        if m[k][k] <= 0:
            return False
        if k == N - 1:
            return m[k][k] == 1
        mk, pk = m[k], m[k][k]
        for i in range(k + 1, N):
            mi, f = m[i], m[i][k]
            for j in range(k + 1, N):
                mi[j] = (mi[j] * pk - f * mk[j]) // prev
        prev = pk


def preserves(G, flat):
    """g^T G g == G for g given row by row."""
    g = [flat[N * i:N * i + N] for i in range(N)]
    Gg = [[sum(G[i][k] * g[k][j] for k in range(N) if G[i][k]) for j in range(N)] for i in range(N)]
    for i in range(N):
        col = [g[k][i] for k in range(N)]
        for j in range(i, N):
            if sum(col[k] * Gg[k][j] for k in range(N) if col[k]) != G[i][j]:
                return False
    return True


def orbit_size(gens, v, cap):
    """The size of the orbit of v under the group generated by gens (v -> g v), or cap + 1 once it exceeds cap."""
    seen, frontier = {v}, [v]
    while frontier:
        nxt = []
        for w in frontier:
            for g in gens:
                u = tuple(sum(map(mul, row, w)) for row in g)
                if u not in seen:
                    seen.add(u)
                    nxt.append(u)
                    if len(seen) > cap:
                        return cap + 1
        frontier = nxt
    return len(seen)


def generates(label, flats, order):
    """True if some orbit has exactly `order` elements (then the generators generate Aut L, see E); else the largest
    orbit size found (> order contradicts the label)."""
    gens = [[flat[N * i:N * i + N] for i in range(N)] for flat in flats]
    gens = [g for g in gens if any(g[i][j] != (i == j) for i in range(N) for j in range(N))]
    rng = random.Random(label)
    best = 1
    for _ in range(TRIES):
        s = orbit_size(gens, tuple(rng.randint(-40, 40) for _ in range(N)), order)
        if s == order:
            return True
        best = max(best, s)
        if s > order:
            break
    return best


def open_asset(path):
    tar = tarfile.open(path)
    members = {m.name.split('/', 1)[1]: m for m in tar.getmembers() if m.isfile()}
    return tar, members


def main():
    args = sys.argv[1:]
    label = None
    if '--label' in args:
        i = args.index('--label')
        label = args[i + 1]
        del args[i:i + 2]
    assets = [a for a in args if a.endswith('.tar.gz')]
    reports = [a for a in args if a.endswith('.json')]
    asset = Path(assets[0]) if assets else ROOT / 'database-v2.tar.gz'
    if not asset.is_file():
        print(f'SKIP database: {asset} not found (download the release asset database-v2.tar.gz to check it)')
        if reports:
            Path(reports[0]).write_text(json.dumps({'checks': [], 'failures': 0, 'skipped': str(asset)}, indent=1) + '\n')
        return
    tar, members = open_asset(asset)
    read = lambda name: tar.extractfile(members[name]).read()
    if label is not None:
        index = {x[0]: x for x in map(json.loads, gzip.decompress(read('index.jsonl.gz')).decode().splitlines())}
        _, f, line = index[label]
        print(gzip.decompress(read(f)).decode().splitlines()[line])
        return
    c = Checks()
    manifest = json.loads(read('MANIFEST.json'))
    files = manifest['files']
    ok, bad = True, []
    for name, info in files.items():
        raw = read(name)
        rows = gzip.decompress(raw).decode().count('\n')
        if len(raw) != info['bytes'] or hashlib.sha256(raw).hexdigest() != info['sha256'] or rows != info['rows']:
            bad.append(name)
    c('A', 'the files of rows have the sizes, digests and numbers of rows of the manifest; 143,329 rows in all',
      not bad and sum(i['rows'] for i in files.values()) == manifest['rows'] == ROWS
      and set(members) == set(files) | {'MANIFEST.json', 'README.md', 'index.jsonl.gz'}, f'{len(files)} files; failures {bad[:3]}')

    classified = {}
    with open(CLASSIFIED) as f:
        for line in f:
            r = json.loads(line)
            classified[r['label']] = r
    index = [json.loads(x) for x in gzip.decompress(read('index.jsonl.gz')).decode().splitlines()]
    labels = [x[0] for x in index]
    c('B', 'the index has every label of data/classified-lattices.jsonl exactly once, in label order',
      len(labels) == len(set(labels)) == ROWS and set(labels) == set(classified)
      and labels == sorted(labels, key=lambda s: (int(s.split('.')[1]), int(s.split('.')[2]))), f'{len(labels)} labels')
    where = {x[0]: (x[1], x[2]) for x in index}

    print(f'asset {asset.name}, version {manifest.get("version")}', flush=True)
    t0, done, bad_gram, bad_gen, bad_row, n_gen = time.time(), 0, [], [], [], 0
    n_orbit, bad_orbit, over_bound = 0, [], []
    for name, info in sorted(files.items()):
        lines = gzip.decompress(read(name)).decode().splitlines()
        for k, line in enumerate(lines):
            r = json.loads(line)
            lab = r['label']
            cl = classified.get(lab)
            if (where.get(lab) != (name, k) or cl is None or cl['part'] != info['part'] or int(lab.split('.')[1]) != cl['aut']
                    or len(r['gram']) != 528 or not r['generators']):
                bad_row.append(lab)
                continue
            G = unpack(r['gram'])
            if any(G[i][i] % 2 for i in range(N)) or not positive_unimodular(G):
                bad_gram.append(lab)
            for g in r['generators']:
                n_gen += 1
                if len(g) != N * N or not all(type(x) is int for x in g) or not preserves(G, g):
                    bad_gen.append(lab)
                    break
            else:
                aut = cl['aut']
                if aut > ORBIT_BOUND:
                    over_bound.append(lab)
                else:
                    n_orbit += 1
                    res = generates(lab, r['generators'], aut)
                    if res is not True:
                        bad_orbit.append([lab, res])
            done += 1
            if done % 10000 == 0:
                print(f'  {done} of {ROWS} lattices, {time.time() - t0:.0f} s', flush=True)
    c('B', 'each row is where the index says, in a file of its part, and the order in its label is |Aut L| of '
           'data/classified-lattices.jsonl', not bad_row, f'failures {bad_row[:3]}')
    c('C', 'each Gram matrix is even, positive definite and of determinant 1', not bad_gram and done == ROWS,
      f'{done} lattices; failures {bad_gram[:3]}')
    c('D', 'each generator is an integer matrix g with g^T G g = G', not bad_gen and done == ROWS,
      f'{n_gen} generators; failures {bad_gen[:3]}; {time.time() - t0:.0f} s')
    c('E', f'for each lattice with |Aut L| <= 10^6, an orbit of the stored generators has |Aut L| elements, so they '
           f'generate Aut L (generation not checked for the {len(over_bound)} lattices with |Aut L| > 10^6)',
      not bad_orbit and n_orbit + len(over_bound) + len(bad_gen) == done == ROWS,
      f'{n_orbit} lattices checked; {len(bad_orbit)} failures {bad_orbit[:3]}; {time.time() - t0:.0f} s; not checked: {sorted(over_bound, key=lambda s: int(s.split(".")[1]))}')

    failures = [x for x in c.results if not x['ok']]
    if reports:
        Path(reports[0]).write_text(json.dumps({'checks': c.results, 'failures': len(failures), 'asset': str(asset)}, indent=1) + '\n')
    print(f'{len(c.results) - len(failures)} of {len(c.results)} checks passed')
    sys.exit(1 if failures else 0)


if __name__ == '__main__':
    main()
