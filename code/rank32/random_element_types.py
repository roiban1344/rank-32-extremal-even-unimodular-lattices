"""Types of automorphisms of odd prime order of known lattices, from random elements of their groups (helpers).

Paper: computation C32 of the first paper; the entry point is code/produce/known_lattices/random_element_types.py.
The type of an element x of prime order p is (p, f, s): f = rank of the fixed lattice, s = p-rank of
the discriminant group of the fixed lattice (its dimension over F_p). grams() collects the Gram matrices of the known lattices
by name: code:NAME (lattices from codes), kmax24:IDX (lattices of the stratum with k_max = 24) and the
ids of the representatives files reps-*.jsonl.
Needs: Sage and numpy.

既知の格子の群のランダムな元から、奇素数位数の自己同型の型を集める（補助の関数）。

論文：第 1 の論文の計算 C32。入口は code/produce/known_lattices/random_element_types.py である。
素数位数 p の元 x の型は (p, f, s)：f = 固定格子の階数、s = 固定格子の判別式群の p-ランク（F_p 上の次元）。
grams() は既知の格子の Gram 行列を名前で集める：code:NAME（符号から作った格子）、kmax24:IDX（k_max = 24 の
層の格子）、代表のファイル reps-*.jsonl の id。
必要なもの：Sage と numpy。
"""
import json
from pathlib import Path

import numpy as np
from sage.all import ZZ, matrix

I = np.eye(32, dtype=np.int64)


def grams(code_grams, kmax24, reps_dir):
    """Gram matrices by name from the files of the lattices from codes, of the stratum k_max = 24, and reps-*.jsonl.

    符号から作った格子、k_max = 24 の層、reps-*.jsonl のファイルから、名前ごとの Gram 行列を集める。"""
    out = {}
    code = json.loads(Path(code_grams).read_text())
    for k, v in code.items():
        out["code:" + k] = v["gram"]
    for l in Path(kmax24).open():
        r = json.loads(l)
        out[f"kmax24:{r['idx']}"] = r["gram"]
    for p in Path(reps_dir).glob("reps-*.jsonl"):
        for l in p.open():
            r = json.loads(l)
            out[r["id"]] = r["gram"]
    return out


def mpow(a, e):
    """a^e for an integer matrix (numpy).

    整数行列（numpy）の a^e。"""
    r = I
    while e:
        if e & 1:
            r = r @ a
        a = a @ a
        e >>= 1
    return r


def fixed_type(G, x, p):
    """(f, s): rank of the fixed lattice of x and p-rank of its discriminant group (dimension over F_p).

    (f, s)：x の固定格子の階数と、その判別式群の p-ランク（F_p 上の次元）。"""
    M = matrix(ZZ, (x - I).tolist())
    B = M.right_kernel().basis_matrix()
    f = B.nrows()
    if f == 0:
        return 0, 0
    F = B * G * B.T
    return f, sum(1 for d in F.elementary_divisors() if d % p == 0)


def class_size(x, gens, inv, cap=3_000_000):
    """Size of the conjugacy class of x under the group generated by gens (None above cap).

    gens の生成する群による x の共役類の大きさ（cap を超えたら None）。"""
    seen = {x.tobytes()}
    fr = [x]
    while fr:
        n = []
        for y in fr:
            for g, h in zip(gens, inv):
                z = g @ y @ h
                k = z.tobytes()
                if k not in seen:
                    seen.add(k)
                    n.append(z)
        fr = n
        if len(seen) > cap:
            return None
    return len(seen)
