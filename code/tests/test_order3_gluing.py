"""Tests of rank32.order3_gluing: the tools on discriminant forms F_3^s, and the 56862 points of sqrt(3) E8.

Time: a few seconds.

rank32.order3_gluing の試験：判別式 F_3^s の道具と、sqrt(3) E8 の 56862 点。

時間：数秒。
"""
import sys
from pathlib import Path

import numpy as np
import pytest

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))   # code/ as the import root / code/ を import の起点にする

sage = pytest.importorskip("sage.all")
from sage.all import CartanMatrix, ZZ, matrix  # noqa: E402

from rank32 import order3_gluing as pg  # noqa: E402


def e8_space():
    E8 = np.array(matrix(ZZ, CartanMatrix(["E", 8])).list(), dtype=np.int64).reshape(8, 8)
    # the discriminant group of F = sqrt(3) E8 is E8/3E8, with the Gram matrix of E8 mod 3 as its form
    # F = sqrt(3) E8 の判別式は E8/3E8 で、形式は E8 の Gram を法 3 で見たもの
    return E8, pg.Space(E8 % 3)


def test_inverse_and_nullspace():
    rng = np.random.default_rng(1)
    E8, sp = e8_space()
    for _ in range(5):
        v = rng.integers(0, 3, size=8)
        if int(v @ sp.B @ v) % 3 == 0:
            continue
        R = pg.reflection(sp.B, v)
        pg.assert_form_preserved(R, sp.B)
        assert ((R @ pg.inv_mod3(R)) % 3 == np.eye(8, dtype=np.int64)).all()
        assert ((R @ R) % 3 == np.eye(8, dtype=np.int64)).all()
    N = pg.nullspace_mod3(np.array([[1, 1, 0, 0, 0, 0, 0, 0]]), 8)
    assert len(N) == 7 and ((N @ np.array([1, 1, 0, 0, 0, 0, 0, 0])) % 3 == 0).all()


def test_anti_isometry():
    rng = np.random.default_rng(2)
    E8, sp = e8_space()
    T = pg.anti_isometry(sp.B, sp.B, rng)
    assert ((T @ sp.B @ T.T + sp.B) % 3 == 0).all()


def test_e8_frames_are_56862():
    """The 120 lines of the roots of E8 have exactly |O_8^+(3)|/|W(E8)| = 56862 images under O_8^+(3).

    E8 のルートの直線 120 本の O_8^+(3) の軌道は、ちょうど |O_8^+(3)|/|W(E8)| = 56862 個。"""
    rng = np.random.default_rng(3)
    E8, sp = e8_space()
    # the roots: vectors of norm 2 (generated by the simple reflections) / ルート：ノルム 2 のベクトル（単純ルートの反射で生成）
    roots = {tuple(np.eye(8, dtype=np.int64)[i]) for i in range(8)}
    todo = list(roots)
    while todo:
        x = np.array(todo.pop())
        for i in range(8):
            y = x.copy()
            y[i] -= int(x @ E8[i])
            t = tuple(int(c) for c in y)
            if t not in roots:
                roots.add(t)
                todo.append(t)
    assert len(roots) == 240
    A = sp.lines_of(np.array(sorted(roots)) % 3)
    assert len(A) == 120
    X = pg.FrameSet(sp, [A], pg.reflection_gens(sp.B, rng, count=12), expected=56862)
    # a reflection permutes X, and element(i) sends point 0 to point i
    # 反射は X の置換で、点 i は element(i) で点 0 から移せる
    g = pg.reflection_gens(sp.B, rng, count=1)[0]
    perm = X.perm_of(g)
    assert len(np.unique(perm)) == X.n
    i = X.n - 1
    h = X.element(i)
    im = np.sort(sp.line_perm(h)[X.pts[0].astype(np.int64)])
    assert (im == X.pts[i]).all()


def test_orbits():
    p = np.array([1, 0, 3, 2, 4])
    label, reps, sizes = pg.orbits([p], 5)
    assert sorted(sizes.tolist()) == [1, 2, 2]
    assert label[0] == label[1] and label[2] == label[3]
